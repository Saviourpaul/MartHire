import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Builds resources/js/world-land.js: a one-degree grid saying which cells are land, for the hero map.
// Land outlines come from Natural Earth (public domain). Run with: node resources/build-world-dots.mjs
const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const TOP = 84; // northern edge of the grid, in degrees latitude
const BOTTOM = -58; // southern edge (skips Antarctica)
const COLUMNS = 360;

const geography = await (await fetch(SOURCE)).json();
const polygons = geography.features
    .flatMap((feature) => (feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates))
    .map((rings) => {
        const xs = rings[0].map(([x]) => x);
        const ys = rings[0].map(([, y]) => y);
        return { rings, minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
    });

const insideRing = (x, y, ring) => {
    let inside = false;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i];
        const [xj, yj] = ring[j];
        if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
    return inside;
};

const isLand = (x, y) => polygons.some((polygon) => (
    x >= polygon.minX && x <= polygon.maxX && y >= polygon.minY && y <= polygon.maxY
    && insideRing(x, y, polygon.rings[0])
    && !polygon.rings.slice(1).some((hole) => insideRing(x, y, hole))
));

const rows = [];
for (let row = 0; row < TOP - BOTTOM; row++) {
    const latitude = TOP - row - 0.5;
    let bits = '';
    for (let column = 0; column < COLUMNS; column++) bits += isLand(column - 180 + 0.5, latitude) ? '1' : '0';
    rows.push(bits.match(/.{4}/g).map((nibble) => parseInt(nibble, 2).toString(16)).join(''));
}

const output = `// Generated by resources/build-world-dots.mjs from Natural Earth land outlines (public domain). Do not edit by hand.
export const LAND_TOP = ${TOP};
export const LAND_COLUMNS = ${COLUMNS};
export const LAND_ROWS = [
${rows.map((row) => `    '${row}',`).join('\n')}
];
`;

writeFileSync(fileURLToPath(new URL('./js/world-land.js', import.meta.url)), output);

// A rough picture in the terminal, to check the grid looks like the world.
const preview = rows.filter((_, index) => index % 4 === 0).map((hex) => {
    const bits = hex.split('').map((digit) => parseInt(digit, 16).toString(2).padStart(4, '0')).join('');
    return bits.split('').filter((_, index) => index % 3 === 0).map((bit) => (bit === '1' ? '#' : ' ')).join('');
});
console.log(preview.join('\n'));
console.log(`\n${rows.length} rows x ${COLUMNS} columns written to resources/js/world-land.js`);
